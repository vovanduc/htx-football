// Duyệt mọi frame kèm khóa định danh (dùng trong test).
export function allFrames() {
  const out = [];
  for (const t of TACTICS) {
    for (const phase of ['attack', 'defend']) out.push({ key: `${t.id}:${phase}`, label: `${t.name} · ${phase === 'attack' ? 'Tấn công' : 'Phòng thủ'}`, frame: t.phases[phase] });
  }
  for (const s of SCENARIOS) out.push({ key: s.id, label: s.name, frame: s.frame });
  return out;
}
